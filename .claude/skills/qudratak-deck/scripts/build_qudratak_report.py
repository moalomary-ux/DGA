def section_divider(s, num, title, sub):
    idx = int(num) - 1
    p1 = find(s, 'prog1'); p2 = find(s, 'prog2')
    p3 = copy.deepcopy(p2._element); p2._element.addnext(p3)
    p3.find('.//' + qn('p:cNvPr')).set('name', 'prog3'); p3.find('.//' + qn('p:cNvPr')).set('id', '9901')
    off = p3.find('.//' + qn('a:off')); off.set('x', str(int(p2.left - (p1.left - p2.left))))
    dashes = [p1, p2, find(s, 'prog3')]
    for i, d in enumerate(dashes):
        set_fill(d, GREEN) if i == idx else set_fill(d, WHITE, alpha=20)
    set_shape_text(find(s, 'big-num'), num)
    t = find(s, 'title'); set_shape_text(t, title)
    text(s, t.left / 914400, t.top / 914400 + 0.75, t.width / 914400, 0.5, sub, size=15, font=F_SEMI, color='9DEBC8', anchor='t')

