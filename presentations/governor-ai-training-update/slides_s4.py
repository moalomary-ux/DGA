def slide_asks(D):
    s = D.content(balance("نرفع أربعة توجيهات لاستكمال العمل المشترك والانتقال إلى التنفيذ"),
                  "المطلوب من معاليكم دعم مواءمة هذا التصور مع الوزارة، وتحديد دور قدراتك والخطوات التالية.", label="asks")
    tag(s, 4)
    asks = [
        ("توجيه", "قدراتك باستكمال توزيع الأدوار مع وزارة الاتصالات وتقنية المعلومات والجهات ذات العلاقة، وتوثيق نطاق مسؤولية الهيئة ومخرجاتها في المسار الحكومي."),
        ("تأييد", "مواءمة نموذج المسارات الثلاثة مع تصنيف الوزارة، مع إطار للحكومة وتنفيذ نوعي متدرج يبدأ بالجهات الخمس ذات الأولوية."),
        ("دعم", "التنسيق مع ملاك بيانات الموظفين والتدريب، وتسمية نقاط اتصال من الجهات الخمس لبناء تشخيص احتياج موثق."),
        ("توجيه", "قدراتك بتطوير حزمة القيادات والمسارات التطبيقية، ورفع خيارات التكلفة والتمويل والجدولة؛ ليُعتمد التنفيذ على نطاق ومتطلبات واضحة."),
    ]
    rh, rg = 0.84, 0.08
    d = 0.62
    for k, (verb, text) in enumerate(asks):
        y = Y_BODY + k * (rh + rg)
        card(s, L_EDGE, y, CW, rh, name=f"توجيه {k + 1}")
        s.number_badge(k + 1, R_EDGE - 0.22 - d, y + (rh - d) / 2, d=d, fill=GREEN, color=NAVY, sz=22)
        vw = 0.95
        s.box("نوع الطلب", R_EDGE - 0.22 - d - 0.2 - vw, y + (rh - 0.38) / 2, vw, 0.38,
              [para(verb, sz=14, color=WHITE, font=F_SEMI, algn="ctr", pitch=20)], geom="roundRect", radius=0.19,
              fill=PURPLE, anchor="ctr", ins=(0, 0, 0, 0), fit=False)
        tx_r = R_EDGE - 0.22 - d - 0.2 - vw - 0.2
        s.text(f"نص {k + 1}", L_EDGE + 0.25, y, tx_r - (L_EDGE + 0.25), rh, [para(text, sz=15, pitch=22)], anchor="ctr")
    by = Y_BODY + 4 * (rh + rg) + 0.04
    banner(s, L_EDGE, by, CW, Y_BODY_END - by,
           [run("سنعود لمعاليكم بـ:  ", sz=14, color=WHITE, font=F_SEMI),
            run("توزيع أدوار متفق عليه، واحتياجات الجهات الأولى، وخيارات برامج وتكلفة وتمويل، ومؤشرات لقياس التطبيق.", sz=14, color=WHITE)],
           fill=NAVY, icon="PiArrowUUpLeft", icon_fg=NAVY, icon_bg=GREEN, sz=14, pitch=20, name="ما سنعود به")
    D.source(s, "الحالة: طلبات توجيه مقترحة لمعالي المحافظ؛ واعتماد الأعداد الكبيرة أو الالتزامات المالية مرتبط باستكمال بياناتها ونطاقها.")
    new_notes(D, s, 18)
    return s
