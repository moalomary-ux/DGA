def slide_plan(D):
    s = D.content(balance("خطة العمل التالية تنتج نطاقًا معتمدًا وبرامج قابلة للتسعير والتنفيذ"),
                  "مراحل مقترحة تبدأ بعد الاتفاق على نطاق العمل وتسمية المسؤولين؛ تُضبط المواعيد بحسب البيانات والتمويل.",
                  label="plan")
    tag(s, 4)
    phases = [
        ("التأسيس", PURPLE,
         "توثيق الأدوار، وتأكيد الجهات الخمس ونقاط الاتصال، وإرسال قالب البيانات، وتحديث حصر البرامج والشركاء.",
         "وثيقة نطاق ومسؤوليات؛ وخطة بيانات بملاك ومواعيد؛ وقائمة أولويات أولية."),
        ("التصميم", TEAL,
         "تشخيص احتياج الجهات، وتحديد شرائح البرامج، واختيار حالات التطبيق، وتطوير عروض القيادات والمحترفين والوعي.",
         "حزمة برامج بمخرجات وأعداد وتكاليف ومؤشرات، وخيارات تمويل وجدولة."),
        ("التجربة والتقييم", NAVY,
         "تنفيذ البرامج التي يُعتمد نطاقها وتتوافر متطلباتها، ومتابعة التطبيق داخل الجهات، ثم مراجعة نتائجها.",
         "نتائج تعلم وتطبيق موثقة؛ وتحسينات على النموذج؛ وتوصية بالتوسع."),
    ]
    g = 0.2
    cw = (CW - 2 * g) / 3
    for k, (nm, col, work, out) in enumerate(phases):
        x = R_EDGE - cw - k * (cw + g)
        chevron(s, x, Y_BODY, cw, 0.66, nm, col, sz=17, name=f"مرحلة {nm}")
        y = Y_BODY + 0.78
        card(s, x, y, cw, 1.42, name=f"عمل {nm}")
        labeled(s, f"عمل {nm} نص", x + 0.2, y + 0.12, cw - 0.4, "العمل", work, label_color=col if col != NAVY else PURPLE)
        y2 = y + 1.42 + 0.08
        card(s, x, y2, cw, 1.12, fill=GREEN_T, name=f"مخرج {nm}")
        labeled(s, f"مخرج {nm} نص", x + 0.2, y2 + 0.12, cw - 0.4, "المخرج القابل للمراجعة", out, label_color="0E8E5F")
    by = Y_BODY + 0.78 + 1.42 + 0.08 + 1.12 + 0.12
    banner(s, L_EDGE, by, CW, Y_BODY_END - by,
           [run("يُقترح تفصيل المراحل في خطة 30 / 60 / 90 يومًا عند اعتماد النطاق.\n", sz=14, color=NAVY, font=F_SEMI),
            run("التحديث القادم للمعالي: مسؤوليات متفق عليها، واحتياج الجهات الأولى، وحزمة البرامج وتكاليفها، وحالة البيانات والتنفيذ.", sz=14, color=NAVY)],
           fill=TEAL_T, icon="PiCalendarCheck", icon_fg=TEAL, icon_bg=WHITE, sz=14, pitch=20, name="الخطة والتحديث القادم")
    D.source(s, "المرجع: تصور مقترح من قدراتك استنادًا إلى مسودة التحديث ووثيقة المهمة الوطنية.  الحالة: خارطة مقترحة؛ ليست التزامًا زمنيًا أو ماليًا معتمدًا.")
    new_notes(D, s, 16)
    return s


