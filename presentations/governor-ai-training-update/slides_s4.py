def slide_measure(D):
    s = D.content("نقيس الوصول والتعلم والتطبيق ثم أثر الاستخدام على العمل",
                  "نضيف متابعة التطبيق إلى مؤشرات الحضور والرضا الحالية، بمؤشرات مناسبة لكل مسار.", label="measure")
    tag(s, 4)
    steps = [
        ("الوصول", "PiUsers", "#1", PURPLE_T, PURPLE, NAVY,
         "عدد المستفيدين الفريدين، والفئات والجهات التي وصلت إليها البرامج، ونسبة التغطية من المستهدف المحدد."),
        ("التعلم", "PiBookOpenText", "#2", "DECBF1", PURPLE, NAVY,
         "تقييم القدرة أو المخرج العملي، إلى جانب إكمال التدريب ورضا المشاركين."),
        ("التطبيق", "PiGearSix", "#3", "BD98E4", NAVY, NAVY,
         "للقيادات قرارات وخطط متابعة؛ وللمحترفين حالات استخدام ومخرجات اختبار؛ ولعموم الموظفين استخدام في مهام مناسبة."),
        ("الأثر", "PiTrendUp", "#4", PURPLE, WHITE, WHITE,
         "قياس تغير الوقت أو جودة المخرج أو إعادة العمل في حالة محددة، مع خط أساس ونطاق مقارنة واضحين."),
    ]
    g = 0.16
    sw = (CW - 3 * g) / 4
    base = 5.52
    heights = [2.58, 2.86, 3.1, 3.32]
    for k, (t, ic, _, fill, tcol, bcol, b) in enumerate(steps):
        x = R_EDGE - sw - k * (sw + g)
        h = heights[k]
        y = base - h
        card(s, x, y, sw, h, fill=fill, radius=0.16, name=f"مستوى {t}")
        s.icon_badge(ic, x + sw - 0.2 - 0.5, y + 0.16, d=0.5, bg=WHITE, fg=PURPLE, scale=0.56)
        s.text(f"عنوان {t}", x + 0.2, y + 0.16, sw - 0.2 - 0.5 - 0.15 - 0.2, 0.5,
               [para(t, sz=19, color=tcol, font=F_SEMI, b=True, pitch=27)], anchor="ctr")
        s.text(f"نص {t}", x + 0.2, y + 0.8, sw - 0.4, h - 0.86, [para(b, sz=14, color=bcol, pitch=20)])
    by = base + 0.16
    banner(s, L_EDGE, by, CW, Y_BODY_END - by,
           [run("المسؤولية:  ", sz=15, color=NAVY, font=F_SEMI),
            run("تسمية مالك للمتابعة داخل كل جهة، وتحديد دور قدراتك والوزارة في تجميع النتائج ومراجعتها ضمن النموذج المتفق عليه.", sz=15, color=NAVY)],
           fill=TEAL_T, icon="PiIdentificationBadge", icon_fg=TEAL, icon_bg=WHITE, sz=15, pitch=22, name="مسؤولية المتابعة")
    D.source(s, "المرجع: وثيقة المهمة الوطنية (ص 2 و3 و7)؛ الدراسة المعيارية (ص 25-26).  الحالة: إطار قياس مقترح؛ لا توجد نتائج أثر إنتاجي شاملة، ولا نذكر مكاسب قبل قياسها.")
    new_notes(D, s, 17)
    return s


