def evidence(D):
    """internal register: rows are packed greedily so that no page overflows"""
    cw_ = [1.0, 3.3, 7.2]
    mg = (0.14, 0.05, 0.14, 0.05)

    def row_h(n):
        t = para(EVIDENCE_TITLES[n], sz=13, font=F_SEMI, pitch=18).height(cw_[1] - mg[0] - mg[2])
        e = para(NOTES[n]["evidence"], sz=13, pitch=18).height(cw_[2] - mg[0] - mg[2])
        return max(0.62, max(t, e) + mg[1] + mg[3])

    avail = Y_BODY_END - Y_BODY - 0.44
    chunks, cur, used = [], [], 0.0
    for n in range(1, 19):
        h = row_h(n)
        if cur and used + h > avail:
            chunks.append(cur)
            cur, used = [], 0.0
        cur.append(n)
        used += h
    if cur:
        chunks.append(cur)
    out = []
    for ci, chunk in enumerate(chunks):
        s = D.content(f"داخلي — سجل الإثبات قبل الاجتماع ({ci + 1}/{len(chunks)})",
                      "قائمة عمل للمراجعة الداخلية؛ تُستكمل قبل تحويل النص إلى عرض معتمد.", label=f"evid-{ci + 1}", kind="internal")
        s.chip("داخلي — للمراجعة فقط", L_EDGE, 0.10, 3.0, 0.30, fill=PURPLE, color=WHITE, sz=11)
        rows = [["الشريحة", "العنوان", "المطلوب إثباته واستكماله"]]
        for n in chunk:
            rows.append([[para(str(n), sz=18, color=PURPLE, font=F_SEMI, algn="ctr", pitch=26)],
                         cell(EVIDENCE_TITLES[n], sz=13, color=NAVY, font=F_SEMI, pitch=18),
                         cell(NOTES[n]["evidence"], sz=13, pitch=18)])
        s.table("سجل الإثبات", L_EDGE, Y_BODY, cw_, rows, min_h=0.62, hdr_h=0.44, max_bottom=Y_BODY_END + 0.05, margins=mg)
        D.notes(s, ["## داخلي", "سجل الإثبات قبل الاجتماع — من النص الأصلي."])
        out.append(s)
    return out
